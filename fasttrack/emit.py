"""Write patch sets, reports and state.

Layout under the output directory:

    patches/6.18/series.conf                    apply order
    patches/6.18/0001-<sha12>-<slug>.patch      upstream patch + X-Fasttrack-* headers
    patches/6.18/base                           stable commit everything was verified on
    patches/6.18/fasttrack.json                 provenance
    unpatched.json                              security fixes that do not apply unchanged
    cve/<ID>/<series>/...                       same layout, per incident
    work/<ID>/<series>/                         backport work packages (BRIEF.md, tree/)

The directory is regenerated from scratch on every run. That is how
expiry works: once a stable release carries a fix, the CVE record or the
queue stops proposing it, and the patch disappears from the next PR.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from .engine import ACCEPTED, CONFLICT, MISSING, OTHER_ARCH, PRESENT, SeriesResult

HEADER = """\
# Generated by ksec-fasttrack. Do not edit by hand: the next run rewrites it.
# Security fixes not yet in a {s} stable release, verified to apply as a series,
# with no fuzz, on top of {head12} ({ver}).
"""


def write_patch_dir(d: Path, series: str, head: str, version: str, patches, extra: dict | None = None) -> Path:
    """(Re)write one patch set. Removed entirely when there is nothing to carry."""
    if d.exists():
        shutil.rmtree(d)
    if not patches:
        return d
    d.mkdir(parents=True)
    lines = [HEADER.format(s=series, head12=head[:12], ver=version)]
    for c in patches:
        (d / c.filename).write_text(_with_provenance(c), encoding="utf-8", errors="surrogateescape")
        lines.append(c.filename)
    (d / "series.conf").write_text("\n".join(lines) + "\n")
    (d / "base").write_text(head + "\n")
    (d / "fasttrack.json").write_text(json.dumps({
        "series": series,
        "base": {"commit": head, "version": version},
        **(extra or {}),
        "patches": [c.public() for c in patches],
    }, indent=2) + "\n")
    return d


def write_series_dir(out: Path, res: SeriesResult, now: str = "") -> Path:
    return write_patch_dir(out / "patches" / res.series, res.series, res.head, res.head_version, res.accepted)


def unpatched(results: list[SeriesResult]) -> list[dict]:
    """Security fixes we know about that are not in the patch set."""
    rows = []
    for r in results:
        for c in r.candidates:
            if c.verdict in (CONFLICT, MISSING):
                rows.append({"series": r.series, "cves": c.cves, "kev": c.kev, "upstream": c.upstream,
                             "subject": c.subject, "verdict": c.verdict, "files": c.files,
                             "prerequisites": c.prerequisites, "reason": c.reason,
                             "build_log": c.build_log})
    return rows


def _with_provenance(c) -> str:
    """Prepend a non-diff header; git apply and Armbian's patcher both skip it."""
    tags = [f"X-Fasttrack-Source: {c.source}"]
    if c.upstream:
        tags.append(f"X-Fasttrack-Upstream: {c.upstream}")
    if c.cves:
        tags.append(f"X-Fasttrack-CVE: {', '.join(c.cves)}")
    if c.kev:
        tags.append("X-Fasttrack-KEV: yes")
    body = c.patch
    if body.startswith("From "):
        first, _, rest = body.partition("\n")
        return first + "\n" + "\n".join(tags) + "\n" + rest
    return "\n".join(tags) + "\n" + body


def report(results: list[SeriesResult], events: list[str]) -> str:
    out = ["# Kernel security fast-track", ""]
    if events:
        out += ["**Events this run**", ""] + [f"- {e}" for e in events] + [""]
    for r in results:
        stale = ""
        if r.upstream_latest and r.upstream_latest != r.head_version:
            stale = f" — kernel.org says {r.upstream_latest}; mirror may be stale"
        out += [f"## {r.series} (base {r.head_version}, `{r.head[:12]}`){stale}", ""]
        # Nothing to do for these: a count is enough; state.json has the list.
        quiet = [f"{title}: {n}" for verdict, title in ((PRESENT, "Already in tree"),
                                                        (OTHER_ARCH, "Other architectures (not built)"))
                 if (n := sum(c.verdict == verdict for c in r.candidates))]
        if quiet:
            out += [" · ".join(quiet), ""]
        groups = [(ACCEPTED, "Included (applies unchanged)"),
                  (CONFLICT, "Needs a manual backport"),
                  (MISSING, "Mainline commit not in mirror")]
        for verdict, title in groups:
            rows = [c for c in r.candidates if c.verdict == verdict]
            if not rows:
                continue
            out += [f"### {title} ({len(rows)})", "",
                    "| | CVE | Upstream | Source | Subject |", "|---|---|---|---|---|"]
            for c in rows:
                flag = " ".join(f for f in ("🔥 KEV" if c.kev else "",
                                            "does not build" if c.build_log else "") if f)
                cves = ", ".join(c.cves) or "—"
                out.append(f"| {flag} | {cves} | `{c.upstream[:12] or '—'}` | {c.source} | {c.subject.replace('|', '/')} |")
            out.append("")
        if any(c.verdict == CONFLICT for c in r.candidates):
            out += ["Fix any of these with `fasttrack cve <ID>` (add `--claude` for a Claude-made backport).", ""]
        if not r.candidates:
            out += ["Nothing pending. The stable branch carries every known fix.", ""]
    return "\n".join(out)


def diff_state(prev: dict, results: list[SeriesResult]) -> tuple[dict, list[str]]:
    """Compare with last run; return new state and human-readable events."""
    events: list[str] = []
    state = {"series": {}}
    for r in results:
        old = prev.get("series", {}).get(r.series, {})
        acc = sorted(c.upstream for c in r.accepted)
        kev = sorted({cve for c in r.candidates if c.kev for cve in c.cves})
        state["series"][r.series] = {"head": r.head, "version": r.head_version,
                                     "accepted": acc, "kev": kev}
        if old.get("version") and old["version"] != r.head_version:
            events.append(f"new-stable {r.series}: {old['version']} → {r.head_version}")
        added = set(acc) - set(old.get("accepted", []))
        dropped = set(old.get("accepted", [])) - set(acc)
        if added:
            events.append(f"added {r.series}: {len(added)} patch(es)")
        if dropped:
            events.append(f"retired {r.series}: {len(dropped)} patch(es) (landed upstream or superseded)")
        for cve in sorted(set(kev) - set(old.get("kev", []))):
            events.append(f"kev {r.series}: {cve} is actively exploited")
    return state, events


def cve_report(resolutions) -> str:
    out = ["# Incident resolution", "",
           "| Incident | Series | Outcome | Patches | Note |", "|---|---|---|---|---|"]
    for r in resolutions:
        out.append(f"| {r.cve} | {r.series} ({r.head_version}) | **{r.outcome}** | {len(r.patches)} | {r.note} |")
    out.append("")
    for r in resolutions:
        if not r.candidates:
            continue
        out += [f"## {r.cve} on {r.series}", ""]
        if r.title:
            out += [r.title, ""]
        for c in r.candidates:
            out.append(f"- `{(c.upstream or c.source)[:12]}` {c.subject} — **{c.verdict}**"
                       + (f": {c.reason}" if c.reason else ""))
            if c.verdict == CONFLICT and c.files:
                out.append(f"  - files: {', '.join(c.files)}")
            for p in c.prerequisites[:8]:
                out.append(f"  - possible prerequisite: `{p}`")
        if r.work_dir:
            out += ["", f"Work package: `{r.work_dir}` (BRIEF.md; run `claude` there, or rerun with `--claude`)"]
        out.append("")
    return "\n".join(out)
